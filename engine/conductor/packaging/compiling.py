"""Behaviour: compiling the catalog (TOOLS) and the constraint registry of an instance.

A `tools:` front matter proposes names; this module is where a name resolves to what
it's FOR. The full contract of a given proc comes with the block instead, the day it is
actually CALLed -- TOOLS is a menu, not the dish.
"""
from __future__ import annotations

import re
from pathlib import Path

from .. import reading
from ..state import instance, persistence, record, settings
from ..core.errors import Refusal
from ..core import language
from ..core.model import Constraint, Tool
from . import contributions, topology

STATE_PARTS = tuple(Path(instance.STATE).parts)
ENGINE_PARTS = (instance.SYS, "engine")
VENDOR_PARTS = tuple(Path(instance.VENDOR).parts)
BORDER = "---"
TAG = re.compile(r"@([A-Za-z0-9_-]+)\.([A-Za-z0-9_-]+)")

RESERVED = tuple(sorted(contributions.SYSTEM_VERBS))   # ONE list: the contract reserves them
PLAYED = ("proc", "boot")   # the kinds whose `proc:` the engine PLAYS -- a flow lives at
                            # either; read here, judged here, said once
# the console's own verbs: the dispatch resolves them BEFORE the skills, so a
# skill under one of these names is unreachable through `pp <name>` -- lint says so


HOMES = (instance.PROCS, "overlays", "skills", instance.SYS)   # the instance's folders the composition
                    # reads, beside the files at its top; any other folder is the operator's matter


def _swept(meta: Path):
    """-> every reachable document of the WHOLE composition, the switches ignored:
    what the registry, the attaches and the lint judge -- off is not gone, and a
    code doubled by a switched package must still refuse when it comes back. The
    instance's documents are its files at the top and those under its HOMES; a working
    folder of the operator -- a plan's matter, a package's records -- composes nothing.
    The machine's run state and its engine copy are not documents of the composition (the
    engine's pattern demonstrations travel with it), `_`-prefixed working files are never
    scanned, and a vendored package's `user/` copies are REFERENCE material (the
    PLACED instance files are the live ones -- sweeping both would double every
    declaration). The catalog reads `_played` instead."""
    homed = list(meta.glob("*.md")) + list(instance.procs_of(meta / instance.PROCS).values())
    homed += [path for home in HOMES if home != instance.PROCS and (meta / home).is_dir()
              for path in (meta / home).rglob("*.md")]
    for path in sorted(homed):
        parts = path.relative_to(meta).parts
        if (parts[:len(STATE_PARTS)] == STATE_PARTS or parts[:len(ENGINE_PARTS)] == ENGINE_PARTS
                or path.name.startswith("_")):
            continue
        if parts[:len(VENDOR_PARTS)] == VENDOR_PARTS and len(parts) > 3 and parts[3] == "user":
            continue
        yield path
    # an instance that BORROWS a machine carries no vendor: the bundles it plays are swept
    # where they live, in the requires topology, with the same exclusions
    for root in instance.vendored(meta, switched=False):
        if root.is_relative_to(meta):
            continue
        shelved = set(instance.procs_of(root / instance.PROCS).values())
        for path in sorted(root.rglob("*.md")):
            rest = path.relative_to(root).parts
            if (path.name.startswith("_") or (rest and rest[0] == "user")
                    or (rest and rest[0] == instance.PROCS and path not in shelved)):
                continue
            yield path


def _played(meta: Path):
    """-> the documents IN PLAY: `_swept` without the vendored packages the switches
    take out (`instance.vendored(meta)`, the same composition every other reader of
    the play sees) -- what the catalog compiles from, so a switched package leaves
    no line in what the agent reads."""
    playing = {root.name for root in instance.vendored(meta)}
    for path in _swept(meta):
        kind, segment = instance.machine_part(meta, path)
        if kind == "vendor" and segment not in playing:
            continue
        yield path
